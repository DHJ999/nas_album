// 从 tool/secrets.json 生成 lib/core/secrets.g.dart。
// secrets.json 与 secrets.g.dart 均不入库（见 .gitignore），构建前先跑：
//   dart tool/gen_secrets.dart   （工作目录：app/）
import 'dart:convert';
import 'dart:io';

void main() {
  final src = File('tool/secrets.json');
  if (!src.existsSync()) {
    stderr.writeln('缺少 tool/secrets.json（可从 secrets.example.json 复制后填写）');
    exit(1);
  }
  final j = jsonDecode(src.readAsStringSync()) as Map<String, dynamic>;
  final salt = j['sign_salt'] as String;
  final key = j['photo_api_key'] as String;
  if (salt.startsWith('<') || key.startsWith('<')) {
    stderr.writeln('secrets.json 仍是占位值，请先填写');
    exit(1);
  }
  File('lib/core/secrets.g.dart').writeAsStringSync(
    '// GENERATED by tool/gen_secrets.dart - do not commit, do not edit by hand.\n'
    "const String kSignSalt = '$salt';\n"
    "const String kPhotoApiKey = '$key';\n",
  );
  // ignore: avoid_print
  print("ok: lib/core/secrets.g.dart generated");
}
